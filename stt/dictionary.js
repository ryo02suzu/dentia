/**
 * 歯科用語 補正辞書 v1（決定的置換）
 *
 * 各ルールは「変換されるべき例(positive)」と「変換されてはいけない通常会話例(negative)」を
 * 検証した上で採用している（test/run.js でも代表ケースを回帰テスト）。
 * 誤変換の“訂正”のみを行い、正しい用語へ略語を付け足す等の“注釈”はしない（意味を変えないため）。
 *
 * STT（文字起こし）が誤変換しやすい歯科用語を、安全に正規表記へ直すための表。
 * ここは「意味を変えない・誤爆しにくい」置換だけを置く（迷ったら入れない）。
 * 文脈依存で危険な置換（例: 単独の「パー」→「Per」）は guarded 側で限定的に扱う。
 *
 * 運用方針：
 *  - ベータで観測した実際の誤変換パターンを少しずつ追加する。
 *  - 歯番・左右の取り違えは臨床的に危険なので、確実なものだけを慎重に登録する。
 *  - 各エントリは { re: 正規表現, to: 置換後, why: メモ } の形。
 *
 * @typedef {{ re: RegExp, to: string, why?: string }} Rule
 */

/* ------------------------------------------------------------------ *
 * 1) 安全な置換（常時適用）
 *    読み仮名・冗長表記 → 正規の略語/記号。前後関係に依存せず誤爆しにくいもの。
 * ------------------------------------------------------------------ */
